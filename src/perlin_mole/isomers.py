def atom_order_map(smiles_a: str, smiles_b: str) -> np.ndarray:
    """Indices into b's atoms, listed in a's atom order (constitution only, chirality ignored).

    SMILES writing does not guarantee atom order (e.g. a mirrored ibuprofen SMILES moves
    the stereocentre from atom 10 to atom 8), so coordinates of b must be re-indexed
    with this map before comparing them atom-by-atom with a.
    """
    ma, mb = Chem.MolFromSmiles(smiles_a), Chem.MolFromSmiles(smiles_b)
    match = mb.GetSubstructMatch(ma, useChirality=False)
    if len(match) != ma.GetNumAtoms():
        raise ValueError("molecules are not constitutionally identical")
    return np.array(match, dtype=np.int64)


def mirror_smiles(smiles: str) -> str:
    """Invert every tetrahedral centre. Atom order may change on output: use atom_order_map()."""
    mol = Chem.MolFromSmiles(smiles)
    for a in mol.GetAtoms():
        tag = a.GetChiralTag()
        if tag == Chem.ChiralType.CHI_TETRAHEDRAL_CW:
            a.SetChiralTag(Chem.ChiralType.CHI_TETRAHEDRAL_CCW)
        elif tag == Chem.ChiralType.CHI_TETRAHEDRAL_CCW:
            a.SetChiralTag(Chem.ChiralType.CHI_TETRAHEDRAL_CW)
    return Chem.MolToSmiles(mol, canonical=False)


def cip_labels(smiles: str, heavy_xyz: np.ndarray | None = None) -> dict[int, str]:
    """CIP labels of stereocentres: from the SMILES, or perceived from 3-D heavy-atom coordinates."""
    mol = Chem.MolFromSmiles(smiles)
    if heavy_xyz is not None:
        conf = Chem.Conformer(mol.GetNumAtoms())
        for i, p in enumerate(heavy_xyz):
            conf.SetAtomPosition(i, p.tolist())
        mol.RemoveAllConformers()
        mol.AddConformer(conf, assignId=True)
        Chem.AssignStereochemistryFrom3D(mol)
    else:
        Chem.AssignStereochemistry(mol, cleanIt=True, force=True)
    return {a.GetIdx(): a.GetProp("_CIPCode") for a in mol.GetAtoms() if a.HasProp("_CIPCode")}


def stereo_fidelity(smiles: str, minima_xyz: list[np.ndarray]) -> float:
    """Fraction of minima whose 3-D stereocentres all carry the input CIP labels."""
    ref = cip_labels(smiles)
    if not ref or not minima_xyz:
        return 1.0
    return float(np.mean([cip_labels(smiles, x) == ref for x in minima_xyz]))


def mirror_match(
    a: list[tuple[float, np.ndarray]],
    b: list[tuple[float, np.ndarray]],
    rmsd: SymmetryRMSD,
    e_tol: float = 0.1,
    rmsd_tol: float = 0.25,
) -> float:
    """Fraction of minima in ``a`` whose mirror image (x -> -x) is in ``b`` with the same energy."""
    if not a or not b:
        return float("nan")
    be = np.array([e for e, _ in b])
    bx = np.stack([x for _, x in b])
    hits = 0
    for e, x in a:
        cand = np.flatnonzero(np.abs(be - e) < e_tol)
        if cand.size and (rmsd.many(x * np.array([-1.0, 1.0, 1.0]), bx[cand]) < rmsd_tol).any():
            hits += 1
    return hits / len(a)
