"""Isomer and enantiomer test suites.

* **Enantiomers.** MMFF94 is achiral, so the conformational landscapes of R and S
  are exact mirror images. A correct pipeline must (i) never invert a stereocentre
  (torsion rotations are proper motions, so any inversion would be a bug) and
  (ii) find mirror-matching minima with identical energies. Proposals that are
  symmetric in Δφ have no handedness bias, so coverage for R and S should be
  statistically indistinguishable.
* **Diastereomers.** Different, not mirror-related, landscapes: we compare global
  minima and search difficulty.
* **Constitutional isomers.** The same formula with different branching changes
  the torsion graph and therefore the topological embedding that Perlin
  correlation is built on. If topology-aware correlation matters, the effect
  should depend on branching.
* **Conformational isomers vs experiment.** Small molecules whose
  gauche/anti energy differences are known from gas-phase experiments. This
  validates the *judge* (MMFF94), not the search.
"""

